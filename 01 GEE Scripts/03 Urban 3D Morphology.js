var Vis   = Config.Visualization                                                                              ;

var BHVis = Vis.BHVis , SVFVis = Vis.SVFVis , SDHVis = Vis.SDHVis , FAIVis = Vis.FAIVis , BCRVis = Vis.BCRVis ;

var ExportMode = 'Stacked' ; // 'Stacked' → 1 GeoTIFF per city | 'Separate' → 1 GeoTIFF per metric

var BandNames  = [ 'BH' , 'SVF' , 'BCR' , 'FAI' , 'SDH' , 'GBA' , 'HybridHeights' , 'nDSM' , 'DSM' , 'FABDEM' ] ;


