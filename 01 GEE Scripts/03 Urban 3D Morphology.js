// [6] Run Everything, Per City
// ————————————————————————————

var RunPipeline = function() {

  TargetCities.forEach(function(CityName) { 

    var City = ProcessCityMorphology(CityName) ;

    // [6.1] Primary Asset Export

    Export.image.toAsset({

      image       : City.Stack.float()                                                 ,

      description : City.Name + '-3D-UM-Asset'                                         ,

      assetId     : Config.AssetRoot + '/3D-UM/' + City.Name + '/' + City.Name + '-3D' ,

      region      : City.Domain                                                        ,

      scale       : 10                                                                 ,

      maxPixels   : Config.MaxPixels                                                   ,

      crs         : City.CRS                                                           ,

      overwrite   : true

    }) ;

    // [6.2] Map Layers

    Map.addLayer( City.Stack.select('BH')  , BHVis  , City.Name + ' | Mean Building Heights (BH)' , false ) ;

    Map.addLayer( City.Stack.select('BCR') , BCRVis , City.Name + ' | Building Cov. Ratio (BCR)'  , false ) ;

    Map.addLayer( City.Stack.select('SVF') , SVFVis , City.Name + ' | Sky View Factor (SVF)'      , false ) ;

    Map.addLayer( City.Stack.select('FAI') , FAIVis , City.Name + ' | Frontal Area Index (FAI)'   , false ) ;

    Map.addLayer( City.Stack.select('SDH') , SDHVis , City.Name + ' | StDev Height (SDH)'         , false ) ;

    // [6.3] Fast Export Suite — Direct From Asset (no recalculation)

    var Asset = ee.Image(Config.AssetRoot + '/3D-UM/' + City.Name + '/' + City.Name + '-3D') ;

    var FullStack = Asset

      .addBands( City.Heights.clip(City.HoldoutGeom).rename('GBA') )

      .addBands( City.HybridHeights.clip(City.HoldoutGeom).rename('HybridHeights') )

      .addBands( nDSM.clip(City.HoldoutGeom).rename('nDSM') )

      .addBands( DSMRaw.clip(City.HoldoutGeom).rename('DSM') )

      .addBands( DTM.clip(City.HoldoutGeom).rename('FABDEM') )

      .toFloat().clip(City.HoldoutGeom) ;

    if (ExportMode === 'Stacked') {

      Export.image.toDrive({

        description    : City.Name + '-3D-UM-Drive'               ,

        fileNamePrefix : City.Name + '-UM'                        ,

        image          : FullStack                                ,

        folder         : 'UC4D/Urban 3D Morphology'               ,

        region         : City.HoldoutGeom                         ,

        scale          : 10                                       ,

        crs            : City.CRS                                 ,

        maxPixels      : Config.MaxPixels                         ,

        fileFormat     : 'GeoTIFF'                                ,

        formatOptions  : { noData : NoData }

      }) ;

    } else {

      BandNames.forEach(function(Band) {

        Export.image.toDrive({

          image          : FullStack.select(Band)     ,

          description    : City.Name + '-' + Band     ,

          folder         : 'UC4D/Urban 3D Morphology' ,

          fileNamePrefix : City.Name + '-' + Band     ,

          region         : City.HoldoutGeom           ,

          scale          : 10                         ,

          crs            : City.CRS                   ,

          maxPixels      : Config.MaxPixels           ,

          fileFormat     : 'GeoTIFF'

        }) ;

      }) ;

    }

  }) ;

} ;
