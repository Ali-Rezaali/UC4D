// [4] Per-City Morphology Pipeline
// ————————————————————————————————

var ProcessCityMorphology = function( CityName ) {

  var Domain     = MergedDomains[CityName] ;

  var CRS        = ResolvedCRS[CityName]   ;

  var Gaps       = CityGapsMap[CityName]   ;

  var nDSMCity   = nDSM.clip(Domain)       ;

  var TileAssets = ResolvedTiles[CityName].map(function(TileName) {

    return ee.FeatureCollection( GBABasePath + '/' + TileName ) ;

  }) ;

  var Buildings = ee.FeatureCollection(TileAssets).flatten()

    .filterBounds(Domain)

    .map(function(f) { return f.set('geo_area', f.geometry().area(1)); })

    .filter(ee.Filter.lt('geo_area', 50000)) ;

  var NoHeights        = Buildings.filter(ee.Filter.or(ee.Filter.eq('height', null), ee.Filter.lte('height', 0)))                                                                   ;

  var WithHeights      = Buildings.filter(ee.Filter.and(ee.Filter.neq('height', null), ee.Filter.gt('height', 0)))                                                                  ;

  var TrainRaster      = ee.Image.constant(0).clip(Domain)                                                                                                                          ;

  var HeightOnlyRaster = TrainRaster.paint({ featureCollection : WithHeights , color : 'height' })                                                                                  ;

  var FilledFC         = nDSMCity.reduceRegions({ collection : NoHeights , reducer : ee.Reducer.mean() , scale : 10 , crs : CRS })                                                  ;

  var nDSMFilledRaster = TrainRaster.paint({ featureCollection : FilledFC , color : 'mean' })                                                                                       ;

  var Heights          = HeightOnlyRaster.max(nDSMFilledRaster)                                                                                                                     ;

  var GBAMask          = Heights.gt(0)                                                                                                                                              ;

  var WSFMask          = Gaps ? WSF2019.clip(Gaps).eq(255) : ee.Image.constant(0).clip(Domain).rename('b1')                                                                         ;

  var GapPixels        = WSFMask.and(GBAMask.not())                                                                                                                                 ;

  var GapnDSM          = nDSMCity.unmask(0)                                                                                                                                         ;

  var HybridHeights    = Heights.where(GapPixels, GapnDSM).rename('height')                                                                                                         ;

  var DSMCity          = HybridHeights.reproject({ crs : CRS , scale : 10 })                                                                                                        ;

  var BH               = DSMCity.updateMask(DSMCity.gt(0)).reduceNeighborhood({ reducer : ee.Reducer.mean()   , kernel : Kernel }).unmask(0).rename('BH')                           ;

  var SVF              = CalculateSVF(DSMCity, Domain, 10)                                                                                                                          ;

  var BCR              = DSMCity.gt(0).reduceNeighborhood({ reducer : ee.Reducer.mean()   , kernel : ee.Kernel.circle(100, 'meters') }).rename('BCR')                               ;

  var SDH              = DSMCity.updateMask(DSMCity.gt(0)).reduceNeighborhood({ reducer : ee.Reducer.stdDev() , kernel : ee.Kernel.circle(100, 'meters') }).unmask(0).rename('SDH') ;

  var FAI              = CalculateFAI(DSMCity, Scale, Kernel)                                                                                                                       ;

  var Stack            = BH.addBands(BCR).addBands(SVF).addBands(FAI).addBands(SDH).clip(Domain)                                                                                    ;

  // [4.1] Gap-Fill Statistics

  var Px = ee.Image.pixelArea();

  var Stats = ee.Dictionary({
 
    Area_With_Height_M2 : Px.updateMask(HeightOnlyRaster.gt(0)).reduceRegion({reducer: ee.Reducer.sum(), geometry: Domain, scale: 10, maxPixels: 1e13, crs: CRS}).get('area'),
 
    Area_nDSM_Filled_M2 : Px.updateMask(nDSMFilledRaster.gt(0).and(HeightOnlyRaster.eq(0))).reduceRegion({reducer: ee.Reducer.sum(), geometry: Domain, scale: 10, maxPixels: 1e13, crs: CRS}).get('area'),
 
    Area_WSF_Gap_M2     : Px.updateMask(GapPixels).reduceRegion({reducer: ee.Reducer.sum(), geometry: Domain, scale: 10, maxPixels: 1e13, crs: CRS}).get('area')
 
  });

  var StatsFC = ee.FeatureCollection([ee.Feature(null, {
 
    city                : CityName                                ,
 
    area_GBA_height_m2  : Stats.get('Area_With_Height_M2')        ,
 
    area_nDSM_filled_m2 : Stats.get('Area_nDSM_Filled_M2')        ,
 
    area_WSF_gap_m2     : Stats.get('Area_WSF_Gap_M2')
 
  })]);

  Export.table.toDrive({
 
    collection     : StatsFC                     ,
 
    description    : CityName + '-Fill-Budget'   ,
 
    folder         : 'UC4D/UC4D-Validation'      ,
 
    fileNamePrefix : CityName + '-Fill-Budget'   ,
 
    fileFormat     : 'CSV'
 
  });
  
  return {

    Name          : CityName                            ,

    Domain        : Domain                              ,

    HoldoutGeom   : HoldoutDomains[CityName].geometry() ,

    CRS           : CRS                                 ,

    Stack         : Stack                               ,

    Heights       : Heights                             ,

    HybridHeights : HybridHeights

  } ;

} ;


